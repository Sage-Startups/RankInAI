function renderActionPlan(ctx: RenderContext) {
  const { doc, data } = ctx;
  sectionHeading(doc, '6. Prioritized action plan', { newPage: true });

  if (data.recommendations.length === 0) {
    paragraph(
      doc,
      'No failing or partial checks were found. There is nothing in the action plan for this audit — re-run it after your next round of content changes to confirm the score holds.',
    );
    return;
  }

  const groups = [
    { key: 'DO_FIRST' as const, color: COLORS.critical },
    { key: 'NEXT_30_DAYS' as const, color: COLORS.fair },
    { key: 'LONGER_TERM' as const, color: COLORS.cyan },
  ];

  for (const group of groups) {
    const items = data.recommendations.filter((r) => r.horizon === group.key);
    if (items.length === 0) continue;

    ensureSpace(doc, 44);
    const y = doc.y;
    doc.roundedRect(MARGIN.left, y, CONTENT_WIDTH, 24, 5).fillColor(group.color).fill();
    doc
      .font('Helvetica-Bold')
      .fontSize(10)
      .fillColor(COLORS.white)
      .text(
        `${HORIZON_LABELS[group.key]} — ${items.length} ${items.length === 1 ? 'action' : 'actions'}`,
        MARGIN.left + 12,
        y + 7,
      );
    doc.y = y + 34;

    for (const rec of items) {
      renderRecommendation(ctx, rec);
    }
    doc.y += 6;
  }
}

function renderRecommendation(ctx: RenderContext, rec: ReportData['recommendations'][number]) {
  const { doc } = ctx;

  ensureSpace(doc, 110);

  doc
    .font('Helvetica-Bold')
    .fontSize(10)
    .fillColor(COLORS.ink)
    .text(`${rec.priority}. ${rec.title}`, MARGIN.left, doc.y, { width: CONTENT_WIDTH });
  doc.y += 2;

  doc
    .font('Helvetica')
    .fontSize(7.5)
    .fillColor(COLORS.muted)
    .text(
      `${rec.categoryLabel}   ·   ${rec.impact.toLowerCase()} impact   ·   ${rec.effort.toLowerCase()} effort`,
      MARGIN.left,
      doc.y,
    );
  doc.y += 8;

  fieldBlock(doc, 'WHY IT MATTERS', rec.whyItMatters);
  fieldBlock(doc, 'EXACT RECOMMENDED CHANGE', rec.recommendedChange);

  if (rec.exampleImplementation) {
    const height = doc.font('Courier').fontSize(7.5).heightOfString(rec.exampleImplementation, {
      width: CONTENT_WIDTH - 20,
    });
    ensureSpace(doc, height + 26);

    doc
      .font('Helvetica-Bold')
      .fontSize(7.5)
      .fillColor(COLORS.muted)
      .text('EXAMPLE IMPLEMENTATION', MARGIN.left, doc.y, { characterSpacing: 0.5 });
    doc.y += 8;

    const boxY = doc.y;
    doc.roundedRect(MARGIN.left, boxY, CONTENT_WIDTH, height + 14, 4).fillColor(COLORS.surface).fill();
    doc
      .font('Courier')
      .fontSize(7.5)
      .fillColor(COLORS.body)
      .text(rec.exampleImplementation, MARGIN.left + 10, boxY + 7, { width: CONTENT_WIDTH - 20 });
    doc.y = boxY + height + 20;
  }

  fieldBlock(doc, 'EXPECTED IMPACT', rec.expectedImpact);

  doc.y += 6;
  doc
    .moveTo(MARGIN.left, doc.y)
    .lineTo(MARGIN.left + CONTENT_WIDTH, doc.y)
    .lineWidth(0.5)
    .strokeColor(COLORS.border)
    .stroke();
  doc.y += 10;
}

function fieldBlock(doc: Doc, label: string, value: string) {
  const height = doc.font('Helvetica').fontSize(8.5).heightOfString(value, { width: CONTENT_WIDTH });
  ensureSpace(doc, height + 18);

  doc
    .font('Helvetica-Bold')
    .fontSize(7.5)
    .fillColor(COLORS.muted)
    .text(label, MARGIN.left, doc.y, { characterSpacing: 0.5 });
  doc.y += 8;
  doc.font('Helvetica').fontSize(8.5).fillColor(COLORS.body).text(value, MARGIN.left, doc.y, {
    width: CONTENT_WIDTH,
  });
  doc.y += 8;
}

