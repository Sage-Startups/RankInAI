/* -------------------------------------------------------------------------- */
/* Page furniture (headers, footers, page numbers)                            */
/* -------------------------------------------------------------------------- */

function paintPageFurniture({ doc, data, brandName, footerNote }: RenderContext) {
  const range = doc.bufferedPageRange();

  for (let i = range.start; i < range.start + range.count; i += 1) {
    doc.switchToPage(i);

    const isCover = i === range.start;

    if (!isCover) {
      // Running header.
      doc
        .font('Helvetica')
        .fontSize(7.5)
        .fillColor(COLORS.muted)
        .text(`${brandName} — AI Visibility Audit`, MARGIN.left, 30, {
          width: CONTENT_WIDTH / 2,
          lineBreak: false,
        });
      doc
        .font('Helvetica')
        .fontSize(7.5)
        .fillColor(COLORS.muted)
        .text(data.businessName, MARGIN.left + CONTENT_WIDTH / 2, 30, {
          width: CONTENT_WIDTH / 2,
          align: 'right',
          lineBreak: false,
        });
      doc
        .moveTo(MARGIN.left, 43)
        .lineTo(MARGIN.left + CONTENT_WIDTH, 43)
        .lineWidth(0.5)
        .strokeColor(COLORS.border)
        .stroke();
    }

    // Footer.
    const footerY = PAGE.height - 42;
    doc
      .moveTo(MARGIN.left, footerY - 8)
      .lineTo(MARGIN.left + CONTENT_WIDTH, footerY - 8)
      .lineWidth(0.5)
      .strokeColor(COLORS.border)
      .stroke();

    const leftNote = data.isDemo
      ? 'DEMO DATA — fictional demonstration report'
      : data.branding.whiteLabel
        ? 'Powered by RankInAI'
        : footerNote;

    doc
      .font('Helvetica')
      .fontSize(7)
      .fillColor(data.isDemo ? COLORS.fair : COLORS.muted)
      .text(leftNote, MARGIN.left, footerY, { width: CONTENT_WIDTH - 70, lineBreak: false });

    doc
      .font('Helvetica')
      .fontSize(7)
      .fillColor(COLORS.muted)
      .text(`Page ${i - range.start + 1} of ${range.count}`, MARGIN.left + CONTENT_WIDTH - 70, footerY, {
        width: 70,
        align: 'right',
        lineBreak: false,
      });
  }

  // Leave the cursor on the last page so nothing is appended accidentally.
  doc.switchToPage(range.start + range.count - 1);
}
