import PDFDocument from 'pdfkit';

import { HORIZON_LABELS } from '@/lib/audit/recommendations';
import { overallScoreInterpretation } from '@/lib/audit/scoring';
import { SEVERITY_LABELS } from '@/lib/audit/types';
import { METHODOLOGY_SUMMARY, REPORT_LIMITATIONS, type ReportData } from '@/lib/report/types';
import { formatDate, scoreBandLabel } from '@/lib/utils';

/**
 * PDF report generation.
 *
 * Uses PDFKit with the built-in Helvetica family rather than a headless
 * browser: it runs anywhere Node runs, needs no Chromium binary on Railway, has
 * no persistent-disk dependency, and produces a deterministic document.
 *
 * Page breaks, headers, footers and page numbers are managed explicitly so no
 * component is ever cut in half.
 */

const PAGE = { width: 595.28, height: 841.89 }; // A4 in points
const MARGIN = { top: 64, bottom: 62, left: 54, right: 54 };
const CONTENT_WIDTH = PAGE.width - MARGIN.left - MARGIN.right;

const COLORS = {
  ink: '#0B1020',
  body: '#2B3350',
  muted: '#5A6480',
  border: '#DFE3EE',
  surface: '#F6F7FB',
  violet: '#5844D8',
  cyan: '#0E7490',
  excellent: '#0F9D6E',
  good: '#0E9BB8',
  fair: '#C77700',
  poor: '#DB6B10',
  critical: '#D0342C',
  white: '#FFFFFF',
} as const;

function scoreColor(score: number): string {
  if (score >= 85) return COLORS.excellent;
  if (score >= 70) return COLORS.good;
  if (score >= 55) return COLORS.fair;
  if (score >= 35) return COLORS.poor;
  return COLORS.critical;
}

type Doc = InstanceType<typeof PDFDocument>;

interface RenderContext {
  doc: Doc;
  data: ReportData;
  brandName: string;
  footerNote: string;
}

/**
 * Generate the full PDF and resolve with the complete buffer.
 */
export async function generateReportPdf(
  data: ReportData,
  options: { footerNote?: string } = {},
): Promise<Buffer> {
  const doc = new PDFDocument({
    size: 'A4',
    margins: MARGIN,
    bufferPages: true,
    autoFirstPage: false,
    info: {
      Title: `AI Visibility Audit — ${data.businessName}`,
      Author: data.branding.whiteLabel && data.branding.companyName ? data.branding.companyName : 'RankInAI',
      Subject: 'AI Visibility and Generative Engine Optimization audit report',
      Creator: 'RankInAI',
      Keywords: 'AI visibility, GEO, generative engine optimization, audit',
    },
  });

  const chunks: Buffer[] = [];
  doc.on('data', (chunk: Buffer) => chunks.push(chunk));

  const finished = new Promise<Buffer>((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  const brandName =
    data.branding.whiteLabel && data.branding.companyName ? data.branding.companyName : 'RankInAI';

  const ctx: RenderContext = {
    doc,
    data,
    brandName,
    footerNote:
      options.footerNote ?? 'Generated by RankInAI — AI visibility and GEO audit platform.',
  };

  renderCover(ctx);
  renderExecutiveSummary(ctx);
  renderCategoryScores(ctx);
  renderStrengthsWeaknesses(ctx);
  renderFindings(ctx);
  renderCompetitors(ctx);
  renderActionPlan(ctx);
  renderPages(ctx);
  renderMethodology(ctx);
  renderLimitations(ctx);

  paintPageFurniture(ctx);

  doc.end();
  return finished;
}

/* -------------------------------------------------------------------------- */
/* Layout helpers                                                             */
/* -------------------------------------------------------------------------- */

function newPage(doc: Doc) {
  doc.addPage({ size: 'A4', margins: MARGIN });
  doc.y = MARGIN.top;
}

/** Ensure `needed` points remain before the footer, otherwise break the page. */
function ensureSpace(doc: Doc, needed: number) {
  if (doc.y + needed > PAGE.height - MARGIN.bottom) {
    newPage(doc);
  }
}

function sectionHeading(doc: Doc, title: string, opts: { newPage?: boolean } = {}) {
  if (opts.newPage) newPage(doc);
  else ensureSpace(doc, 70);

  doc
    .fillColor(COLORS.ink)
    .font('Helvetica-Bold')
    .fontSize(15)
    .text(title, MARGIN.left, doc.y, { width: CONTENT_WIDTH });

  const y = doc.y + 6;
  doc
    .moveTo(MARGIN.left, y)
    .lineTo(MARGIN.left + CONTENT_WIDTH, y)
    .lineWidth(1)
    .strokeColor(COLORS.violet)
    .stroke();

  doc.y = y + 14;
}

function paragraph(
  doc: Doc,
  text: string,
  opts: { size?: number; color?: string; font?: string; gap?: number; indent?: number } = {},
) {
  const size = opts.size ?? 9.5;
  const width = CONTENT_WIDTH - (opts.indent ?? 0);
  const height = doc.font(opts.font ?? 'Helvetica').fontSize(size).heightOfString(text, { width });

  ensureSpace(doc, height + 6);

  doc
    .font(opts.font ?? 'Helvetica')
    .fontSize(size)
    .fillColor(opts.color ?? COLORS.body)
    .text(text, MARGIN.left + (opts.indent ?? 0), doc.y, { width, align: 'left' });

  doc.y += opts.gap ?? 8;
}

function labelValue(doc: Doc, label: string, value: string, x: number, y: number, width: number) {
  doc.font('Helvetica').fontSize(7.5).fillColor(COLORS.muted).text(label.toUpperCase(), x, y, { width });
  doc.font('Helvetica-Bold').fontSize(10).fillColor(COLORS.ink).text(value, x, y + 11, { width });
}

/** Horizontal score bar. */
function scoreBar(doc: Doc, x: number, y: number, width: number, score: number, available = true) {
  const height = 6;
  doc.roundedRect(x, y, width, height, 3).fillColor(COLORS.border).fill();
  if (available && score > 0) {
    doc
      .roundedRect(x, y, Math.max(3, (width * Math.max(0, Math.min(100, score))) / 100), height, 3)
      .fillColor(scoreColor(score))
      .fill();
  }
}

function bulletList(doc: Doc, items: string[], opts: { color?: string } = {}) {
  for (const item of items) {
    const height = doc.font('Helvetica').fontSize(9.5).heightOfString(item, {
      width: CONTENT_WIDTH - 14,
    });
    ensureSpace(doc, height + 8);

    doc
      .circle(MARGIN.left + 3, doc.y + 4.5, 1.8)
      .fillColor(opts.color ?? COLORS.violet)
      .fill();

    doc
      .font('Helvetica')
      .fontSize(9.5)
      .fillColor(COLORS.body)
      .text(item, MARGIN.left + 14, doc.y, { width: CONTENT_WIDTH - 14 });

    doc.y += 6;
  }
}

/* -------------------------------------------------------------------------- */
/* 1. Cover                                                                    */
/* -------------------------------------------------------------------------- */

function renderCover({ doc, data, brandName }: RenderContext) {
  newPage(doc);

  // Dark header band.
  doc.rect(0, 0, PAGE.width, 232).fillColor(COLORS.ink).fill();

  // Wordmark (drawn, not an image, so no external asset is required).
  doc.font('Helvetica-Bold').fontSize(17).fillColor(COLORS.white).text(brandName, MARGIN.left, 48);

  doc
    .font('Helvetica')
    .fontSize(8)
    .fillColor('#A3ADC9')
    .text('AI VISIBILITY & GEO AUDIT REPORT', MARGIN.left, 72, { characterSpacing: 1.6 });

  doc
    .font('Helvetica-Bold')
    .fontSize(25)
    .fillColor(COLORS.white)
    .text(data.businessName, MARGIN.left, 108, { width: CONTENT_WIDTH });

  doc
    .font('Helvetica')
    .fontSize(10)
    .fillColor('#A3ADC9')
    .text(data.websiteUrl, MARGIN.left, doc.y + 4, { width: CONTENT_WIDTH });

  if (data.isDemo) {
    doc
      .roundedRect(PAGE.width - MARGIN.right - 120, 44, 120, 22, 5)
      .fillColor('#F59E0B')
      .fill();
    doc
      .font('Helvetica-Bold')
      .fontSize(9)
      .fillColor('#3A2A05')
      .text('DEMO DATA', PAGE.width - MARGIN.right - 120, 51, { width: 120, align: 'center' });
  }

  // Metadata strip.
  const metaY = 178;
  const colWidth = CONTENT_WIDTH / 4;
  const meta: Array<[string, string]> = [
    ['Audit date', formatDate(data.auditDate, 'long')],
    ['Pages analyzed', String(data.pagesCrawled)],
    ['Industry', data.industry ?? 'Not specified'],
    ['Target market', data.targetCountry],
  ];
  meta.forEach(([label, value], index) => {
    const x = MARGIN.left + colWidth * index;
    doc.font('Helvetica').fontSize(7).fillColor('#8792AE').text(label.toUpperCase(), x, metaY, {
      width: colWidth - 8,
      characterSpacing: 0.8,
    });
    doc
      .font('Helvetica-Bold')
      .fontSize(9.5)
      .fillColor(COLORS.white)
      .text(value, x, metaY + 12, { width: colWidth - 8 });
  });

  // Score block.
  doc.y = 272;
  const boxY = doc.y;
  doc
    .roundedRect(MARGIN.left, boxY, CONTENT_WIDTH, 132, 8)
    .fillColor(COLORS.surface)
    .fill()
    .roundedRect(MARGIN.left, boxY, CONTENT_WIDTH, 132, 8)
    .lineWidth(1)
    .strokeColor(COLORS.border)
    .stroke();

  // Score gauge drawn with arcs.
  const cx = MARGIN.left + 78;
  const cy = boxY + 66;
  const radius = 42;
  doc.circle(cx, cy, radius).lineWidth(10).strokeColor(COLORS.border).stroke();

  const fraction = Math.max(0, Math.min(100, data.overallScore)) / 100;
  if (fraction > 0) {
    const start = -Math.PI / 2;
    const end = start + fraction * Math.PI * 2;
    doc.save();
    doc.lineWidth(10).strokeColor(scoreColor(data.overallScore)).lineCap('round');
    // Approximate the arc with short segments — reliable across viewers.
    const steps = Math.max(2, Math.ceil(fraction * 60));
    doc.moveTo(cx + radius * Math.cos(start), cy + radius * Math.sin(start));
    for (let i = 1; i <= steps; i += 1) {
      const angle = start + ((end - start) * i) / steps;
      doc.lineTo(cx + radius * Math.cos(angle), cy + radius * Math.sin(angle));
    }
    doc.stroke();
    doc.restore();
  }

  doc
    .font('Helvetica-Bold')
    .fontSize(26)
    .fillColor(scoreColor(data.overallScore))
    .text(String(data.overallScore), cx - 40, cy - 16, { width: 80, align: 'center' });
  doc
    .font('Helvetica')
    .fontSize(8)
    .fillColor(COLORS.muted)
    .text('out of 100', cx - 40, cy + 13, { width: 80, align: 'center' });

  const textX = MARGIN.left + 154;
  const textWidth = CONTENT_WIDTH - 168;
  doc
    .font('Helvetica-Bold')
    .fontSize(12)
    .fillColor(COLORS.ink)
    .text(
      `Overall AI Visibility Score: ${data.overallScore}/100 (${scoreBandLabel(data.overallScore)})`,
      textX,
      boxY + 24,
      { width: textWidth },
    );
  doc
    .font('Helvetica')
    .fontSize(9)
    .fillColor(COLORS.body)
    .text(overallScoreInterpretation(data.overallScore), textX, doc.y + 5, { width: textWidth });

  if (data.previousScore != null) {
    const delta = data.overallScore - data.previousScore;
    doc
      .font('Helvetica-Bold')
      .fontSize(8.5)
      .fillColor(delta >= 0 ? COLORS.excellent : COLORS.critical)
      .text(
        `Previous audit: ${data.previousScore} (${delta >= 0 ? '+' : ''}${delta})`,
        textX,
        doc.y + 6,
        { width: textWidth },
      );
  }

  doc.y = boxY + 152;

  if (data.isDemo) {
    doc
      .roundedRect(MARGIN.left, doc.y, CONTENT_WIDTH, 52, 6)
      .fillColor('#FDF3E0')
      .fill()
      .roundedRect(MARGIN.left, doc.y, CONTENT_WIDTH, 52, 6)
      .lineWidth(1)
      .strokeColor('#E7B85C')
      .stroke();
    doc
      .font('Helvetica-Bold')
      .fontSize(9)
      .fillColor('#7A5200')
      .text('DEMONSTRATION DATA', MARGIN.left + 12, doc.y + 10, { width: CONTENT_WIDTH - 24 });
    doc
      .font('Helvetica')
      .fontSize(8.5)
      .fillColor('#7A5200')
      .text(
        `Every figure in this report is fictional and was created for product demonstration. ${data.businessName} is not a real company and no website was audited to produce these results.`,
        MARGIN.left + 12,
        doc.y + 2,
        { width: CONTENT_WIDTH - 24 },
      );
    doc.y += 26;
  }

  doc.y = Math.max(doc.y, 480);

  // Contents.
  doc.font('Helvetica-Bold').fontSize(10).fillColor(COLORS.ink).text('Contents', MARGIN.left, doc.y);
  doc.y += 8;
  const contents = [
    '1. Executive summary',
    '2. Category scores',
    '3. Key strengths and critical weaknesses',
    '4. Detailed findings by category',
    '5. Competitor comparison',
    '6. Prioritized action plan',
    '7. Page-by-page observations',
    '8. Methodology',
    '9. Limitations and disclaimer',
  ];
  for (const line of contents) {
    doc.font('Helvetica').fontSize(9).fillColor(COLORS.body).text(line, MARGIN.left + 6, doc.y);
    doc.y += 3;
  }
}

/* -------------------------------------------------------------------------- */
/* 2. Executive summary                                                        */
/* -------------------------------------------------------------------------- */

function renderExecutiveSummary(ctx: RenderContext) {
  const { doc, data } = ctx;
  sectionHeading(doc, '1. Executive summary', { newPage: true });
  paragraph(doc, data.executiveSummary, { size: 10, gap: 12 });

  if (data.llmEnhanced) {
    paragraph(
      doc,
      `This summary was rewritten for clarity by ${data.llmModel ?? 'an AI model'} on ${formatDate(
        data.llmGeneratedAt,
        'datetime',
      )}. Scores and evidence are computed by the rule-based audit engine and were not altered.`,
      { size: 8, color: COLORS.muted, gap: 10 },
    );
  }

  const rows: Array<[string, string]> = [
    ['Business', data.businessName],
    ['Website', data.websiteUrl],
    ['Pages crawled', `${data.pagesCrawled} of up to ${data.pageLimit}`],
    ['Findings recorded', String(data.findings.length)],
    ['Recommendations', String(data.recommendations.length)],
    ['Competitors compared', String(data.competitors.filter((c) => c.overallScore != null).length)],
  ];

  ensureSpace(doc, rows.length * 18 + 20);
  const tableY = doc.y;
  doc.roundedRect(MARGIN.left, tableY, CONTENT_WIDTH, rows.length * 18 + 12, 6).fillColor(COLORS.surface).fill();

  rows.forEach(([label, value], index) => {
    const y = tableY + 8 + index * 18;
    doc.font('Helvetica').fontSize(9).fillColor(COLORS.muted).text(label, MARGIN.left + 12, y, {
      width: 150,
    });
    doc
      .font('Helvetica-Bold')
      .fontSize(9)
      .fillColor(COLORS.ink)
      .text(value, MARGIN.left + 168, y, { width: CONTENT_WIDTH - 180 });
  });

  doc.y = tableY + rows.length * 18 + 24;
}

/* -------------------------------------------------------------------------- */
/* 3. Category scores                                                          */
/* -------------------------------------------------------------------------- */

function renderCategoryScores(ctx: RenderContext) {
  const { doc, data } = ctx;
  sectionHeading(doc, '2. Category scores');

  for (const category of data.categories) {
    const summaryHeight = doc.font('Helvetica').fontSize(8.5).heightOfString(category.summary, {
      width: CONTENT_WIDTH - 24,
    });
    const blockHeight = 46 + summaryHeight;
    ensureSpace(doc, blockHeight + 10);

    const y = doc.y;
    doc
      .roundedRect(MARGIN.left, y, CONTENT_WIDTH, blockHeight, 6)
      .lineWidth(1)
      .strokeColor(COLORS.border)
      .stroke();

    doc
      .font('Helvetica-Bold')
      .fontSize(10)
      .fillColor(COLORS.ink)
      .text(category.label, MARGIN.left + 12, y + 10, { width: CONTENT_WIDTH - 90 });

    doc
      .font('Helvetica-Bold')
      .fontSize(14)
      .fillColor(category.available ? scoreColor(category.score) : COLORS.muted)
      .text(
        category.available ? String(category.score) : '—',
        PAGE.width - MARGIN.right - 60,
        y + 8,
        { width: 48, align: 'right' },
      );

    doc
      .font('Helvetica')
      .fontSize(7.5)
      .fillColor(COLORS.muted)
      .text(
        `${Math.round(category.effectiveWeight * 100)}% weight`,
        PAGE.width - MARGIN.right - 60,
        y + 25,
        { width: 48, align: 'right' },
      );

    scoreBar(doc, MARGIN.left + 12, y + 28, CONTENT_WIDTH - 90, category.score, category.available);

    doc
      .font('Helvetica')
      .fontSize(8.5)
      .fillColor(COLORS.body)
      .text(category.summary, MARGIN.left + 12, y + 40, { width: CONTENT_WIDTH - 24 });

    doc.y = y + blockHeight + 8;
  }
}

