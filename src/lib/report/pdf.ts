/* 5. Findings                                                                 */
/* -------------------------------------------------------------------------- */

function renderFindings(ctx: RenderContext) {
  const { doc, data } = ctx;
  sectionHeading(doc, '4. Detailed findings by category', { newPage: true });

  for (const category of data.categories.filter((c) => c.available)) {
    const findings = data.findings.filter((f) => f.category === category.category);
    if (findings.length === 0) continue;

    ensureSpace(doc, 60);
    doc
      .font('Helvetica-Bold')
      .fontSize(11.5)
      .fillColor(COLORS.violet)
      .text(`${category.label} — ${category.score}/100`, MARGIN.left, doc.y);
    doc.y += 8;

    for (const finding of findings) {
      renderFinding(ctx, finding);
    }
    doc.y += 6;
  }
}

function renderFinding(ctx: RenderContext, finding: ReportData['findings'][number]) {
  const { doc } = ctx;

  const explanationHeight = doc.font('Helvetica').fontSize(8.5).heightOfString(finding.explanation, {
    width: CONTENT_WIDTH - 20,
  });
  const actionHeight =
    finding.status === 'PASS'
      ? 0
      : doc.font('Helvetica').fontSize(8.5).heightOfString(finding.recommendedAction, {
          width: CONTENT_WIDTH - 20,
        }) + 18;

  const evidenceLines = evidenceSummary(finding.evidence);
  const evidenceHeight =
    evidenceLines.length > 0
      ? doc.font('Helvetica').fontSize(7.5).heightOfString(evidenceLines.join('\n'), {
          width: CONTENT_WIDTH - 20,
        }) + 14
      : 0;

  const total = 34 + explanationHeight + actionHeight + evidenceHeight;
  ensureSpace(doc, total + 12);

  const y = doc.y;
  const accent =
    finding.status === 'PASS'
      ? COLORS.excellent
      : finding.status === 'FAIL'
        ? COLORS.critical
        : finding.status === 'WARN'
          ? COLORS.fair
          : COLORS.cyan;

  // Left accent rule.
  doc.rect(MARGIN.left, y, 2.5, total).fillColor(accent).fill();

  doc
    .font('Helvetica-Bold')
    .fontSize(9.5)
    .fillColor(COLORS.ink)
    .text(finding.title, MARGIN.left + 10, y, { width: CONTENT_WIDTH - 110 });

  doc
    .font('Helvetica-Bold')
    .fontSize(7.5)
    .fillColor(accent)
    .text(SEVERITY_LABELS[finding.severity].toUpperCase(), PAGE.width - MARGIN.right - 92, y + 1, {
      width: 92,
      align: 'right',
      characterSpacing: 0.5,
    });

  doc
    .font('Helvetica')
    .fontSize(7)
    .fillColor(COLORS.muted)
    .text(finding.checkId, MARGIN.left + 10, y + 13, { width: CONTENT_WIDTH - 110 });

  doc
    .font('Helvetica')
    .fontSize(8.5)
    .fillColor(COLORS.body)
    .text(finding.explanation, MARGIN.left + 10, y + 24, { width: CONTENT_WIDTH - 20 });

  let cursor = y + 24 + explanationHeight + 6;

  if (finding.status !== 'PASS') {
    doc
      .font('Helvetica-Bold')
      .fontSize(7.5)
      .fillColor(COLORS.muted)
      .text('RECOMMENDED ACTION', MARGIN.left + 10, cursor, { characterSpacing: 0.5 });
    cursor += 10;
    doc
      .font('Helvetica')
      .fontSize(8.5)
      .fillColor(COLORS.ink)
      .text(finding.recommendedAction, MARGIN.left + 10, cursor, { width: CONTENT_WIDTH - 20 });
    cursor = doc.y + 4;
    doc
      .font('Helvetica')
      .fontSize(7.5)
      .fillColor(COLORS.muted)
      .text(
        `Effort: ${finding.effort.toLowerCase()}   ·   Impact: ${finding.impact.toLowerCase()}`,
        MARGIN.left + 10,
        cursor,
      );
    cursor += 12;
  }

  if (evidenceLines.length > 0) {
    doc
      .font('Helvetica-Bold')
      .fontSize(7.5)
      .fillColor(COLORS.muted)
      .text('EVIDENCE OBSERVED', MARGIN.left + 10, cursor, { characterSpacing: 0.5 });
    cursor += 10;
    doc
      .font('Helvetica')
      .fontSize(7.5)
      .fillColor(COLORS.body)
      .text(evidenceLines.join('\n'), MARGIN.left + 10, cursor, { width: CONTENT_WIDTH - 20 });
    cursor = doc.y + 4;
  }

  doc.y = Math.max(cursor, y + total) + 8;
}

function evidenceSummary(evidence: Record<string, unknown>): string[] {
  return Object.entries(evidence ?? {})
    .filter(([, value]) => value !== null && value !== undefined && value !== '')
    .slice(0, 8)
    .map(([key, value]) => `${key}: ${formatEvidence(value)}`);
}

function formatEvidence(value: unknown): string {
  if (typeof value === 'boolean') return value ? 'yes' : 'no';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return value.length > 160 ? `${value.slice(0, 160)}…` : value;
  if (Array.isArray(value)) {
    if (value.length === 0) return 'none';
    const rendered = value
      .slice(0, 5)
      .map((v) => (typeof v === 'object' ? JSON.stringify(v) : String(v)))
      .join(', ');
    return rendered.length > 200 ? `${rendered.slice(0, 200)}…` : rendered;
  }
  const json = JSON.stringify(value);
  return json.length > 200 ? `${json.slice(0, 200)}…` : json;
}

/* -------------------------------------------------------------------------- */
/* 6. Competitors                                                              */
/* -------------------------------------------------------------------------- */

function renderCompetitors(ctx: RenderContext) {
  const { doc, data } = ctx;
  sectionHeading(doc, '5. Competitor comparison', { newPage: true });

  if (data.competitors.length === 0) {
    paragraph(
      doc,
      'No competitor was supplied for this audit, so Competitive Visibility was marked unavailable and its 5% weight was redistributed across the other six categories. Add a competitor URL when you re-run this audit to see the comparison.',
    );
    return;
  }

  paragraph(
    doc,
    'Competitor scores are derived from a single public homepage fetch, not a full crawl. They compare homepage-level signals only.',
    { size: 8.5, color: COLORS.muted },
  );

  const analyzed = data.competitors.filter((c) => c.overallScore != null);
  ensureSpace(doc, (analyzed.length + 1) * 26 + 16);

  const rows: Array<{ label: string; score: number; bold: boolean }> = [
    { label: `${data.businessName} (you)`, score: data.overallScore, bold: true },
    ...analyzed.map((c) => ({
      label: c.name ?? c.url,
      score: c.overallScore ?? 0,
      bold: false,
    })),
  ];

  for (const row of rows) {
    ensureSpace(doc, 26);
    doc
      .font(row.bold ? 'Helvetica-Bold' : 'Helvetica')
      .fontSize(9)
      .fillColor(COLORS.ink)
      .text(row.label, MARGIN.left, doc.y, { width: CONTENT_WIDTH - 44, ellipsis: true });
    doc
      .font('Helvetica-Bold')
      .fontSize(9)
      .fillColor(scoreColor(row.score))
      .text(String(row.score), PAGE.width - MARGIN.right - 34, doc.y - 11, {
        width: 34,
        align: 'right',
      });
    scoreBar(doc, MARGIN.left, doc.y + 2, CONTENT_WIDTH - 44, row.score);
    doc.y += 16;
  }

  doc.y += 8;

  for (const competitor of data.competitors) {
    ensureSpace(doc, 90);
    doc
      .font('Helvetica-Bold')
      .fontSize(10)
      .fillColor(COLORS.ink)
      .text(competitor.name ?? 'Competitor', MARGIN.left, doc.y, { width: CONTENT_WIDTH });
    doc.font('Helvetica').fontSize(8).fillColor(COLORS.muted).text(competitor.url, MARGIN.left, doc.y + 1);
    doc.y += 8;

    if (competitor.error) {
      paragraph(doc, competitor.error, { size: 8.5, color: COLORS.muted });
      continue;
    }

    if (competitor.highlights.length > 0) {
      doc
        .font('Helvetica-Bold')
        .fontSize(8)
        .fillColor(COLORS.excellent)
        .text('WHAT THEY DO WELL', MARGIN.left, doc.y, { characterSpacing: 0.5 });
      doc.y += 4;
      bulletList(doc, competitor.highlights, { color: COLORS.excellent });
    }

    if (competitor.gaps.length > 0) {
      doc
        .font('Helvetica-Bold')
        .fontSize(8)
        .fillColor(COLORS.fair)
        .text('WHERE THEY ARE WEAK', MARGIN.left, doc.y, { characterSpacing: 0.5 });
      doc.y += 4;
      bulletList(doc, competitor.gaps, { color: COLORS.fair });
    }

    doc.y += 8;
  }
}

