function renderPages(ctx: RenderContext) {
  const { doc, data } = ctx;
  sectionHeading(doc, '7. Page-by-page observations', { newPage: true });

  const columns = [
    { label: 'Page', width: 210 },
    { label: 'Status', width: 46 },
    { label: 'Words', width: 46 },
    { label: 'Schema', width: 125 },
    { label: 'Role', width: 60 },
  ];

  const drawHeader = () => {
    const y = doc.y;
    doc.rect(MARGIN.left, y, CONTENT_WIDTH, 20).fillColor(COLORS.surface).fill();
    let x = MARGIN.left + 8;
    for (const column of columns) {
      doc.font('Helvetica-Bold').fontSize(7.5).fillColor(COLORS.muted).text(column.label.toUpperCase(), x, y + 6, {
        width: column.width - 8,
        characterSpacing: 0.5,
      });
      x += column.width;
    }
    doc.y = y + 24;
  };

  drawHeader();

  for (const page of data.pages) {
    const label = page.title ?? page.url;
    const labelHeight = doc.font('Helvetica').fontSize(8).heightOfString(label, { width: 202 });
    const rowHeight = Math.max(24, labelHeight + 16);

    if (doc.y + rowHeight > PAGE.height - MARGIN.bottom) {
      newPage(doc);
      drawHeader();
    }

    const y = doc.y;
    let x = MARGIN.left + 8;

    doc.font('Helvetica').fontSize(8).fillColor(COLORS.ink).text(label, x, y, { width: 202 });
    doc
      .font('Helvetica')
      .fontSize(6.5)
      .fillColor(COLORS.muted)
      .text(page.url, x, doc.y, { width: 202, ellipsis: true });
    x += columns[0]!.width;

    doc
      .font('Helvetica')
      .fontSize(8)
      .fillColor(page.error ? COLORS.critical : COLORS.body)
      .text(page.statusCode != null ? String(page.statusCode) : '—', x, y, { width: 38 });
    x += columns[1]!.width;

    doc.font('Helvetica').fontSize(8).fillColor(COLORS.body).text(page.wordCount ? String(page.wordCount) : '—', x, y, {
      width: 38,
    });
    x += columns[2]!.width;

    doc
      .font('Helvetica')
      .fontSize(7.5)
      .fillColor(COLORS.body)
      .text(page.schemaTypes.length > 0 ? page.schemaTypes.slice(0, 3).join(', ') : 'none', x, y, {
        width: 117,
      });
    x += columns[3]!.width;

    doc
      .font('Helvetica')
      .fontSize(7.5)
      .fillColor(COLORS.muted)
      .text(page.role.replace(/_/g, ' ').toLowerCase(), x, y, { width: 54 });

    doc.y = y + rowHeight;
    doc
      .moveTo(MARGIN.left, doc.y - 4)
      .lineTo(MARGIN.left + CONTENT_WIDTH, doc.y - 4)
      .lineWidth(0.5)
      .strokeColor(COLORS.border)
      .stroke();
  }

  if (data.robotsSummary) {
    doc.y += 12;
    ensureSpace(doc, 80);
    doc.font('Helvetica-Bold').fontSize(10).fillColor(COLORS.ink).text('Site-level files', MARGIN.left, doc.y);
    doc.y += 8;
    bulletList(doc, [
      `robots.txt: ${data.robotsSummary.found ? 'found' : 'not found'}`,
      `XML sitemap: ${
        data.robotsSummary.sitemapFound
          ? `found (${data.robotsSummary.sitemapUrlCount} URLs)`
          : 'not found'
      }`,
      `llms.txt: ${data.robotsSummary.llmsTxtFound ? 'found' : 'not found'}`,
      `AI crawlers blocked: ${
        data.robotsSummary.blockedAiAgents.length > 0
          ? data.robotsSummary.blockedAiAgents.join(', ')
          : 'none'
      }`,
    ]);
  }
}

